// Writes docs/public-surface.txt: every name an installation, script or agent can depend on, one per
// line. scripts/check-breaking-changes.ts compares it between a pull request and its base, so a
// removed or renamed name needs a breaking changelog fragment.
//   bun run docs:surface

import { writeFile } from "node:fs/promises";
import path from "node:path";

import { z } from "zod";

import { GLOBAL_OPTIONS, type Command } from "../src/cli/command";
import { COMMANDS } from "../src/cli/main";
import { BUILTIN_FILES } from "../src/config/builtin";
import { configSchema, nativeStageSchema } from "../src/config/schema";
import type { Plugin } from "../src/core/plugins";
import { EVENT_CATALOGUE } from "../src/events/catalogue";
import { PLUGINS } from "../src/plugins";
import { createTaskRegistry } from "../src/tasks/catalogue";

const HEADER = [
  "# Public surface: generated by scripts/generate-public-surface.ts. Do not edit by hand; run `bun run docs:surface`.",
  "# Removing or renaming a line is a breaking change: its changelog fragment needs `breaking: true`.",
];

type JsonSchema = {
  type?: string | string[];
  properties?: Record<string, JsonSchema>;
  additionalProperties?: JsonSchema | boolean;
  items?: JsonSchema;
  anyOf?: JsonSchema[];
  oneOf?: JsonSchema[];
  allOf?: JsonSchema[];
};

/** Every key path an input object accepts: `<name>` stands for a key the operator chooses, `[]` for a list entry. */
export function keyPaths(schema: JsonSchema, prefix = "", depth = 0): string[] {
  if (depth > 12) return [];
  const paths: string[] = [];
  for (const branch of [...(schema.anyOf ?? []), ...(schema.oneOf ?? []), ...(schema.allOf ?? [])]) paths.push(...keyPaths(branch, prefix, depth + 1));
  for (const [key, child] of Object.entries(schema.properties ?? {})) {
    const at = prefix ? `${prefix}.${key}` : key;
    paths.push(at, ...keyPaths(child, at, depth + 1));
  }
  if (typeof schema.additionalProperties === "object") paths.push(...keyPaths(schema.additionalProperties, prefix ? `${prefix}.<name>` : "<name>", depth + 1));
  if (schema.items) paths.push(...keyPaths(schema.items, `${prefix}[]`, depth + 1));
  return paths;
}

const inputKeys = (schema: z.ZodType): string[] => keyPaths(z.toJSONSchema(schema, { io: "input", unrepresentable: "any" }) as JsonSchema);

/** The label names a packaged provider definition uses. */
export function labelNames(providersYaml: string): string[] {
  const parsed = Bun.YAML.parse(providersYaml) as { items?: Record<string, { labels?: unknown }> };
  const names: string[] = [];
  const collect = (value: unknown): void => {
    if (typeof value === "string") names.push(value);
    else if (value && typeof value === "object") for (const child of Object.values(value)) collect(child);
  };
  for (const provider of Object.values(parsed.items ?? {})) collect(provider.labels);
  return names;
}

export interface SurfaceSources {
  commands: readonly Command[];
  globalOptions: Record<string, unknown>;
  events: Record<string, { payload: z.ZodType }>;
  tasks: ReadonlyArray<{ name: string; config?: z.ZodType; input?: z.ZodType }>;
  config: z.ZodType;
  /** The shipped plugins: their provider schemas add the keys of `sources`, `codeHosts` and `ci` entries. */
  plugins: readonly Plugin[];
  /** A stage of the installation stage list; the config schema accepts stages as opaque values. */
  stage: z.ZodType;
  builtinFiles: readonly string[];
  labels: readonly string[];
}

function defaultSources(): SurfaceSources {
  return {
    commands: COMMANDS,
    globalOptions: GLOBAL_OPTIONS,
    events: EVENT_CATALOGUE,
    tasks: createTaskRegistry().list(),
    config: configSchema,
    plugins: PLUGINS,
    stage: nativeStageSchema,
    builtinFiles: Object.keys(BUILTIN_FILES),
    labels: labelNames(BUILTIN_FILES["providers.yaml"] ?? ""),
  };
}

/** The sorted, unique lines of docs/public-surface.txt, without its header. */
export function publicSurface(sources: SurfaceSources = defaultSources()): string[] {
  const lines = new Set<string>();
  for (const name of Object.keys(sources.globalOptions)) lines.add(`cli-option --${name}`);
  for (const command of sources.commands) {
    lines.add(`cli conveyor ${command.name}`);
    for (const option of Object.keys(command.options ?? {})) lines.add(`cli-option conveyor ${command.name} --${option}`);
  }
  for (const [type, definition] of Object.entries(sources.events)) {
    lines.add(`event ${type}`);
    for (const field of inputKeys(definition.payload)) lines.add(`event-field ${type} ${field}`);
  }
  for (const task of sources.tasks) {
    lines.add(`task ${task.name}`);
    if (task.config) for (const key of inputKeys(task.config)) lines.add(`task-config ${task.name} ${key}`);
    if (task.input) for (const key of inputKeys(task.input)) lines.add(`task-input ${task.name} ${key}`);
  }
  for (const key of inputKeys(sources.config)) lines.add(`config ${key}`);
  const section = { items: "sources", code: "codeHosts", ci: "ci" } as const;
  for (const plugin of sources.plugins) {
    if (plugin.role === "harness") continue;
    for (const key of inputKeys(plugin.configSchema)) lines.add(`config ${section[plugin.role]}.<name>.${key}`);
  }
  for (const key of inputKeys(sources.stage)) lines.add(`config stages[].${key}`);
  for (const file of sources.builtinFiles) lines.add(`builtin ${file}`);
  for (const label of sources.labels) lines.add(`label ${label}`);
  return [...lines].sort();
}

export function renderPublicSurface(sources?: SurfaceSources): string {
  return `${[...HEADER, ...publicSurface(sources)].join("\n")}\n`;
}

/** The surface lines of a docs/public-surface.txt text, without comments. */
export function parsePublicSurface(text: string): string[] {
  return text.split("\n").map((line) => line.trim()).filter((line) => line && !line.startsWith("#"));
}

if (import.meta.main) {
  const target = path.join(import.meta.dir, "../docs/public-surface.txt");
  await writeFile(target, renderPublicSurface());
  console.log(`Wrote ${target}`);
}
